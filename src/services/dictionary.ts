/**
 * Preserves the casing of the original source word (e.g. "Eten" -> "Eat", "essen" -> "eat")
 */
function preserveCapitalization(original: string, translated: string): string {
  if (!original || !translated) return translated;
  const trimmed = original.trim();
  if (!trimmed) return translated;

  const firstChar = trimmed[0];
  if (firstChar === firstChar.toUpperCase() && firstChar !== firstChar.toLowerCase()) {
    return translated[0].toUpperCase() + translated.slice(1);
  }
  return translated;
}

/**
 * Searches the local offline dictionary for exact phrase or vocabulary match.
 * Guarantees zero-latency translations for common terms across all supported languages.
 */
export function lookupOfflineDictionary(
  text: string,
  from: LanguageCode,
  to: LanguageCode
): string | null {
  const trimmed = text.trim();
  if (!trimmed) return '';

  const sFrom = (from || '').trim().toLowerCase() as LanguageCode;
  const sTo = (to || '').trim().toLowerCase() as LanguageCode;

  // Strict check: if source matches target or either is empty, do not translate
  if (!sFrom || !sTo || sFrom === sTo) {
    return '';
  }

  const lower = trimmed.toLowerCase();

  // 1. Exact phrase lookup in COMMON_PHRASES
  for (const item of COMMON_PHRASES) {
    const fromVal = item[sFrom];
    const toVal = item[sTo];
    if (fromVal && toVal && fromVal.toLowerCase().trim() === lower) {
      if (toVal.toLowerCase().trim() !== lower) {
        return preserveCapitalization(trimmed, toVal);
      }
    }
  }

  // 2. Phrase lookup stripped of common punctuation
  const cleanTrimmed = lower.replace(/[.,/#!$%^&*;:{}=\-_`~()?]/g, '').trim();
  for (const item of COMMON_PHRASES) {
    const fromVal = item[sFrom];
    const toVal = item[sTo];
    if (fromVal && toVal) {
      const cleanItem = fromVal.toLowerCase().replace(/[.,/#!$%^&*;:{}=\-_`~()?]/g, '').trim();
      if (cleanItem === cleanTrimmed) {
        if (toVal.toLowerCase().trim() !== cleanTrimmed) {
          return preserveCapitalization(trimmed, toVal);
        }
      }
    }
  }

  // 3. Exact single/multi word lookup in WORD_MAP
  for (const entry of Object.values(WORD_MAP)) {
    const fromVal = entry[sFrom];
    const toVal = entry[sTo];
    if (fromVal && toVal) {
      const cleanFromVal = fromVal.toLowerCase().trim();
      if (cleanFromVal === lower || cleanFromVal === cleanTrimmed) {
        if (toVal.toLowerCase().trim() !== lower) {
          return preserveCapitalization(trimmed, toVal);
        }
      }
    }
  }

  // 4. Token-by-token translation for short phrases (2 to 4 words)
  const words = cleanTrimmed.split(/\s+/);
  if (words.length > 1 && words.length <= 4) {
    const translatedWords: string[] = [];
    let matchCount = 0;

    for (const w of words) {
      let foundWord = '';
      for (const entry of Object.values(WORD_MAP)) {
        const fromVal = entry[sFrom];
        const toVal = entry[sTo];
        if (fromVal && toVal && fromVal.toLowerCase().trim() === w) {
          if (toVal.toLowerCase().trim() !== w) {
            foundWord = toVal;
            matchCount++;
            break;
          }
        }
      }
      translatedWords.push(foundWord || w);
    }

    if (matchCount > 0) {
      const assembled = translatedWords.join(' ');
      if (assembled.toLowerCase() !== lower) {
        return preserveCapitalization(trimmed, assembled);
      }
    }
  }

  return null;
}
